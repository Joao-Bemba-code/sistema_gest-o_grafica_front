const TONS = {
  pagamento: LuBanknote,
  dinheiro: LuWallet,
  troco: LuCoins,
  imposto: LuPercent,
  multa: LuCircleDollarSign,
};

export default function Icon({ name, className, wrapClassName, ...props }) {
  const Icone = ICONES[name] || TONS[name];
  if (Icone) {
    return <Icone aria-hidden="true" className={className} {...props} />;
  }
  // Fallback seguro: nunca mostrar o nome em texto se o ícone não existir.
  return <LuInfo aria-hidden="true" className={className} {...props} />;
}
